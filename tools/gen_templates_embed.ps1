param(
    [string]$TemplatesDir,
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
if (-not $TemplatesDir) { $TemplatesDir = Join-Path $root 'templates' }
if (-not $OutFile) { $OutFile = Join-Path $root 'build_gen\templates_embed.c' }

if (-not (Test-Path $TemplatesDir)) {
    Write-Error "templates directory not found: $TemplatesDir"
    exit 1
}

$files = Get-ChildItem -Path $TemplatesDir -Recurse -File |
    Where-Object { $_.FullName -notmatch '\\\.gradle\\' -and $_.Name -notlike '*.lock' } |
    Sort-Object FullName

function ConvertTo-CLiteral([byte[]]$bytes) {
    $sb = New-Object System.Text.StringBuilder
    foreach ($b in $bytes) {
        if ($b -eq 10) { [void]$sb.Append('\n') }
        elseif ($b -eq 13) { [void]$sb.Append('\r') }
        elseif ($b -eq 9) { [void]$sb.Append('\t') }
        elseif ($b -eq 34) { [void]$sb.Append('\"') }
        elseif ($b -eq 92) { [void]$sb.Append('\\') }
        elseif ($b -ge 32 -and $b -le 126 -and $b -ne 63) { [void]$sb.Append([char]$b) }
        else {
            $oct = [Convert]::ToString($b, 8).PadLeft(3, '0')
            [void]$sb.Append(('\{0}' -f $oct))
        }
    }
    return $sb.ToString()
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Generated by tools/gen_templates_embed.ps1 - do not edit. */')
[void]$sb.AppendLine('#include "embed.h"')
[void]$sb.AppendLine('')

$entries = @()
$i = 0
foreach ($f in $files) {
    $rel = $f.FullName.Substring($TemplatesDir.Length).TrimStart('\', '/').Replace('\', '/')
    $bytes = [System.IO.File]::ReadAllBytes($f.FullName)
    $lit = ConvertTo-CLiteral $bytes
    [void]$sb.AppendLine("static const char TPL_$i[] = `"$lit`";")
    $entries += "    { `"$rel`", TPL_$i, $($bytes.Length) }"
    $i++
}

[void]$sb.AppendLine('')
[void]$sb.AppendLine('const DpTplFile DP_TPL_FILES[] = {')
foreach ($e in $entries) { [void]$sb.AppendLine($e + ',') }
[void]$sb.AppendLine('    { NULL, NULL, 0 }')
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('')

$sigSrc = ($files | ForEach-Object {
    "$($_.FullName.Substring($TemplatesDir.Length)):$($_.Length)"
}) -join '|'
$md5 = [System.Security.Cryptography.MD5]::Create()
$hash = $md5.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($sigSrc))
$sig = -join ($hash | ForEach-Object { $_.ToString('x2') })

[void]$sb.AppendLine("const char *DP_TPL_SIG = `"$sig`";")

$outDir = Split-Path -Parent $OutFile
if ($outDir -and -not (Test-Path $outDir)) {
    New-Item -ItemType Directory -Force -Path $outDir | Out-Null
}
[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

Write-Host ("  embedded {0} template files -> {1}" -f $files.Count, $OutFile)